export function computeAgencySellerPayoutMetrics(
  agencies: AgencyRecord[],
  sellers: SellerRecord[],
  payouts: PayoutRecord[]
): AgencySellerPayoutMetrics {
  const totalAgencies = agencies.length;
  const activeAgencies = agencies.filter((a) => a.status === 'Active').length;
  const pendingAgencies = agencies.filter((a) => a.status === 'Pending').length;
  const suspendedAgencies = agencies.filter((a) => a.status === 'Suspended').length;

  const totalSellers = sellers.length;
  const activeSellers = sellers.filter((s) => s.status === 'Active').length;
  const pendingSellers = sellers.filter((s) => s.status === 'Pending').length;

  const totalPayoutRequests = payouts.length;
  const pendingPayoutRequests = payouts.filter((p) => p.status === 'Pending').length;
  const underReviewPayoutRequests = payouts.filter((p) => p.status === 'Under Review').length;
  const approvedPayoutRequests = payouts.filter((p) => p.status === 'Approved').length;
  const rejectedPayoutRequests = payouts.filter((p) => p.status === 'Rejected').length;
  const completedPayouts = payouts.filter((p) => p.status === 'Completed').length;

  const totalDemoPayoutAmountUsd = payouts.reduce((acc, p) => acc + p.requestedDemoAmountUsd, 0);
  const totalDemoPayoutAmountPkr = payouts.reduce((acc, p) => acc + p.requestedDemoAmountPkr, 0);

  const agencyPayoutAmountUsd = payouts
    .filter((p) => p.accountType === 'Agency')
    .reduce((acc, p) => acc + p.requestedDemoAmountUsd, 0);

  const sellerPayoutAmountUsd = payouts
    .filter((p) => p.accountType === 'Coin Seller')
    .reduce((acc, p) => acc + p.requestedDemoAmountUsd, 0);

  const pendingPayoutAmountUsd = payouts
    .filter((p) => p.status === 'Pending' || p.status === 'Under Review')
    .reduce((acc, p) => acc + p.requestedDemoAmountUsd, 0);

  const approvedPayoutAmountUsd = payouts
    .filter((p) => p.status === 'Approved')
    .reduce((acc, p) => acc + p.requestedDemoAmountUsd, 0);

  const completedPayoutAmountUsd = payouts
    .filter((p) => p.status === 'Completed')
    .reduce((acc, p) => acc + p.requestedDemoAmountUsd, 0);

  return {
    totalAgencies,
    activeAgencies,
    pendingAgencies,
    suspendedAgencies,
    totalSellers,
    activeSellers,
    pendingSellers,
    totalPayoutRequests,
    pendingPayoutRequests,
    underReviewPayoutRequests,
    approvedPayoutRequests,
    rejectedPayoutRequests,
    completedPayouts,
    totalDemoPayoutAmountUsd,
    totalDemoPayoutAmountPkr,
    agencyPayoutAmountUsd,
    sellerPayoutAmountUsd,
    pendingPayoutAmountUsd,
    approvedPayoutAmountUsd,
    completedPayoutAmountUsd,
  };
}
