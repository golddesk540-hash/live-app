export function computeEconomyMetrics(
  content: ContentRecord[],
  gifts: GiftRecord[],
  packages: CoinPackageRecord[],
  virtualItems: VirtualItemRecord[],
  storeItems: StoreContentRecord[]
): EconomyMetrics {
  const activeGifts = gifts.filter((g) => g.status === 'Active').length;
  const categoriesSet = new Set(gifts.map((g) => g.category));
  const availablePackages = packages.filter((p) => p.status === 'Active').length;
  const pendingReview = content.filter((c) => c.status === 'Pending Review').length;

  return {
    totalContentItems: content.length,
    activeGifts,
    totalGiftCategories: categoriesSet.size,
    availableCoinPackages: availablePackages,
    virtualItemsCount: virtualItems.length,
    contentPendingReview: pendingReview,
    totalCoinCirculation: 14850000,
    dailyCoinVolume: 1121000,
    weeklyCoinVolume: 6910000,
    monthlyCoinVolume: 21500000,
    activeStoreItems: storeItems.filter((s) => s.status === 'Active').length,
  };
}
