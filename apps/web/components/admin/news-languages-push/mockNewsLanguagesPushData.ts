export function computeNewsLanguagesPushMetrics(
  articles: NewsArticleRecord[],
  languages: LanguageRecord[],
  campaigns: CampaignRecord[]
): NewsLanguagesPushMetrics {
  const totalNews = articles.length;
  const publishedNews = articles.filter((a) => a.status === 'Published').length;
  const draftNews = articles.filter((a) => a.status === 'Draft').length;
  const scheduledNews = articles.filter((a) => a.status === 'Scheduled').length;
  const archivedNews = articles.filter((a) => a.status === 'Archived').length;

  const totalLanguages = languages.length;
  const activeLanguages = languages.filter((l) => l.status === 'Active').length;

  const totalPossibleKeys = languages.reduce((sum, l) => sum + l.totalKeys, 0);
  const totalCompletedKeys = languages.reduce((sum, l) => sum + l.completedKeys, 0);
  const translationOverallPercentage = totalPossibleKeys > 0
    ? Math.round((totalCompletedKeys / totalPossibleKeys) * 100)
    : 100;

  const totalCampaigns = campaigns.length;
  const scheduledCampaigns = campaigns.filter((c) => c.status === 'Scheduled').length;
  const sentCampaigns = campaigns.filter((c) => c.status === 'Sent Demo').length;
  const draftCampaigns = campaigns.filter((c) => c.status === 'Draft').length;

  const totalRecipients = campaigns
    .filter((c) => c.status === 'Sent Demo')
    .reduce((sum, c) => sum + c.deliveredCount, 0);

  return {
    totalNews,
    publishedNews,
    draftNews,
    scheduledNews,
    archivedNews,
    totalLanguages,
    activeLanguages,
    translationOverallPercentage,
    totalCampaigns,
    scheduledCampaigns,
    sentCampaigns,
    draftCampaigns,
    totalRecipients,
  };
}
