'use client';

import React, { useState } from 'react';
import {
  AlertCircle,
  AlertTriangle,
  ArrowRight,
  CheckCircle2,
  Filter,
  Flame,
  Search,
  Shield,
  ShieldAlert,
  Sparkles,
  X,
} from 'lucide-react';
import { ChildSafetyEmptyStates } from './ChildSafetyEmptyStates';
import {
  SafetyAlertCategory,
  SafetyAlertRecord,
  SafetyCaseRecord,
  SafetyPriority,
} from './childSafetyTypes';

interface SafetyAlertsListViewProps {
  alerts: SafetyAlertRecord[];
  allCases: SafetyCaseRecord[];
  onSelectCaseById: (caseId: string) => void;
  onRefresh: () => void;
}

export const SafetyAlertsListView: React.FC<SafetyAlertsListViewProps> = ({
  alerts,
  allCases,
  onSelectCaseById,
  onRefresh,
}) => {
  const [searchQuery, setSearchQuery] = useState<string>('');
  const [selectedCategory, setSelectedCategory] = useState<string>('All');
  const [selectedPriority, setSelectedPriority] = useState<string>('All');

  const categories = [
    { key: 'All', label: 'All Categories' },
    { key: 'age_concern', label: 'Age-Related Concern' },
    { key: 'potential_minor', label: 'Minor Safety Concern' },
    { key: 'inappropriate_interaction', label: 'Inappropriate Interaction' },
    { key: 'harassment_concern', label: 'Harassment Concern' },
    { key: 'suspicious_activity', label: 'Suspicious Activity' },
    { key: 'policy_concern', label: 'Policy Concern' },
  ];

  const filteredAlerts = alerts.filter((a) => {
    if (selectedCategory !== 'All' && a.category !== selectedCategory) return false;
    if (selectedPriority !== 'All' && a.priority !== selectedPriority) return false;
    if (searchQuery.trim()) {
      const q = searchQuery.toLowerCase().trim();
      const matchId = a.id.toLowerCase().includes(q);
      const matchUser = a.relatedUsername.toLowerCase().includes(q);
      const matchReport = a.relatedReportId.toLowerCase().includes(q);
      const matchDesc = a.shortDescription.toLowerCase().includes(q);
      if (!matchId && !matchUser && !matchReport && !matchDesc) return false;
    }
    return true;
  });

  return (
    <div className="space-y-6 animate-fadeIn">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3">
        <div>
          <h2 className="text-xl font-extrabold text-white flex items-center gap-2">
            <AlertTriangle className="w-5 h-5 text-amber-400" />
            Safety Alerts Stream
            <span className="text-xs px-2.5 py-0.5 rounded-full bg-amber-500/20 text-amber-300 font-bold border border-amber-500/30">
              {alerts.length} Total Alerts
            </span>
          </h2>
          <p className="text-xs text-gray-400 mt-1">
            Real-time incident detection feeds generated by automated content classifiers and user reports
          </p>
        </div>

        <button
          onClick={onRefresh}
          className="self-start sm:self-auto px-3.5 py-1.5 rounded-xl text-xs font-semibold bg-white/5 hover:bg-white/10 text-gray-300 border border-white/10"
        >
          Refresh Feed
        </button>
      </div>

      {/* Filter and Search Bar */}
      <div className="p-4 rounded-2xl bg-[#1A103C]/80 border border-white/10 space-y-3">
        <div className="flex flex-col md:flex-row md:items-center justify-between gap-3">
          <div className="relative flex-1 max-w-md">
            <Search className="absolute left-3.5 top-1/2 -translate-y-1/2 w-4 h-4 text-gray-400" />
            <input
              type="text"
              placeholder="Search by Alert ID, target user, report ID..."
              value={searchQuery}
              onChange={(e) => setSearchQuery(e.target.value)}
              className="w-full pl-10 pr-9 py-2 rounded-xl bg-[#0B0716] border border-white/15 text-xs text-white placeholder-gray-500 focus:outline-none focus:border-pink-500"
            />
            {searchQuery && (
              <button
                onClick={() => setSearchQuery('')}
                className="absolute right-3 top-1/2 -translate-y-1/2 text-gray-400 hover:text-white"
              >
                <X className="w-3.5 h-3.5" />
              </button>
            )}
          </div>

          <div className="flex flex-wrap items-center gap-2">
            <select
              value={selectedCategory}
              onChange={(e) => setSelectedCategory(e.target.value)}
              aria-label="Filter alerts by incident classification category"
              className="px-3 py-2 rounded-xl bg-[#0B0716] border border-white/15 text-xs text-white focus:outline-none focus:border-pink-500"
            >
              {categories.map((c) => (
                <option key={c.key} value={c.key}>
                  {c.label}
                </option>
              ))}
            </select>

            <select
              value={selectedPriority}
              onChange={(e) => setSelectedPriority(e.target.value)}
              aria-label="Filter alerts by threat priority level"
              className="px-3 py-2 rounded-xl bg-[#0B0716] border border-white/15 text-xs text-white focus:outline-none focus:border-pink-500"
            >
              <option value="All">All Priorities</option>
              <option value="Urgent">Urgent</option>
              <option value="High">High</option>
              <option value="Medium">Medium</option>
              <option value="Low">Low</option>
            </select>

            {(searchQuery || selectedCategory !== 'All' || selectedPriority !== 'All') && (
              <button
                onClick={() => {
                  setSearchQuery('');
                  setSelectedCategory('All');
                  setSelectedPriority('All');
                }}
                className="px-3 py-2 rounded-xl text-xs font-semibold text-rose-300 bg-rose-500/10 hover:bg-rose-500/20 border border-rose-500/30"
              >
                Clear
              </button>
            )}
          </div>
        </div>
      </div>

      {/* Alerts Grid */}
      {filteredAlerts.length === 0 ? (
        <ChildSafetyEmptyStates
          type={searchQuery ? 'no_search_results' : 'no_alerts'}
          onResetFilters={() => {
            setSearchQuery('');
            setSelectedCategory('All');
            setSelectedPriority('All');
          }}
          onRefresh={onRefresh}
        />
      ) : (
        <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-4">
          {filteredAlerts.map((alert) => {
            const isUrgent = alert.priority === 'Urgent';
            return (
              <div
                key={alert.id}
                className={`p-5 rounded-2xl bg-gradient-to-br from-[#1A103C] to-[#120A2A] border transition-all duration-300 flex flex-col justify-between ${
                  isUrgent
                    ? 'border-rose-500/50 shadow-[0_0_20px_rgba(244,63,94,0.2)]'
                    : 'border-white/10 hover:border-pink-500/40'
                }`}
              >
                <div>
                  <div className="flex items-center justify-between mb-2">
                    <span className="font-mono text-xs font-bold text-white">
                      {alert.id}
                    </span>
                    <span className="text-[10px] text-gray-400">{alert.createdRelative}</span>
                  </div>

                  <div className="flex items-center justify-between mb-2">
                    <span className="text-xs font-bold text-pink-400 truncate">
                      {alert.categoryLabel}
                    </span>
                    <span
                      className={`px-2 py-0.5 rounded-full text-[9px] font-bold border ${
                        isUrgent
                          ? 'bg-rose-500/20 text-rose-300 border-rose-500/40'
                          : 'bg-amber-500/20 text-amber-300 border-amber-500/40'
                      }`}
                    >
                      {alert.priority}
                    </span>
                  </div>

                  <p className="text-xs text-gray-200 leading-relaxed line-clamp-3 mb-4">
                    {alert.shortDescription}
                  </p>
                </div>

                <div className="pt-3 border-t border-white/5 space-y-2.5 text-xs">
                  <div className="flex items-center justify-between text-gray-400 text-[11px]">
                    <span>
                      Target: <strong className="text-white">{alert.relatedUsername}</strong>
                    </span>
                    <span className="font-mono text-gray-400">
                      Report: {alert.relatedReportId}
                    </span>
                  </div>

                  <div className="flex items-center justify-between">
                    <div className="flex items-center gap-1.5 text-[11px]">
                      <span className="text-gray-400">Risk Score:</span>
                      <span
                        className={`font-bold ${
                          alert.riskScore > 80
                            ? 'text-rose-400'
                            : alert.riskScore > 60
                            ? 'text-amber-400'
                            : 'text-emerald-400'
                        }`}
                      >
                        {alert.riskScore}/100
                      </span>
                    </div>

                    {alert.relatedCaseId ? (
                      <button
                        onClick={() => onSelectCaseById(alert.relatedCaseId!)}
                        className="px-3 py-1.5 rounded-xl bg-pink-500 hover:bg-pink-600 text-white font-bold text-xs shadow-md transition-all active:scale-95"
                      >
                        Review Case
                      </button>
                    ) : (
                      <span className="text-gray-500 text-[10px]">Direct Alert</span>
                    )}
                  </div>
                </div>
              </div>
            );
          })}
        </div>
      )}
    </div>
  );
};
